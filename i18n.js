(() => {
  let language = 'zh';
  try { language = localStorage.getItem('xingtu-language') === 'en' ? 'en' : 'zh'; } catch {}
  function apply(next, notify = true) {
    const previous = language;
    language = next === 'en' ? 'en' : 'zh';
    const translate = key => translations[key]?.[language] ?? key;
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    document.querySelectorAll('[data-i18n]').forEach(el => el.innerHTML = translate(el.dataset.i18n));
    for (const [attribute, data] of [['aria-label','i18nAria'], ['alt','i18nAlt']]) {
      document.querySelectorAll(`[data-${data.replace(/[A-Z]/g, c => '-'+c.toLowerCase())}]`).forEach(el => el.setAttribute(attribute, translate(el.dataset[data])));
    }
    document.title = translate('meta.title');
    document.querySelector('meta[name="description"]').content = translate('meta.description');
    document.querySelector('.language-toggle').setAttribute('aria-label', language === 'zh' ? 'Switch to English' : '切换为中文');
    try { localStorage.setItem('xingtu-language',language); } catch {}
    if (notify) window.dispatchEvent(new CustomEvent('languagechange',{detail:{language,previous}}));
  }
  document.querySelector('.language-toggle').addEventListener('click', () => apply(language === 'zh' ? 'en' : 'zh'));
  apply(language, false);
})();
